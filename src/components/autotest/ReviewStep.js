"use client";

/**
 * Reviewing a generated paper before it is printed.
 *
 * The paper is laid out as it will print — sections in the school's own order,
 * numbering running across the whole paper — with a control beside each
 * question. Rewrite asks the AI for a different question of the same type and
 * the same marks, so the blueprint total never moves; Replace does the same
 * but is told not to repeat the one on screen; Drop removes it, and the tally
 * shows the paper is now short.
 *
 * A type the AI cannot write yet still has its place on the paper: the
 * heading, the numbering and the answer space are printed, and the teacher
 * writes those few by hand.
 */

import { useMemo, useState } from "react";
import { groupIntoSections, questionTypeLabel } from "@/lib/testBlueprints";

const card = {
  background: "#fff", borderRadius: 16,
  border: "1px solid rgba(99,102,241,0.1)", padding: "20px 22px",
};

const btn = {
  width: "100%", padding: "9px 14px", borderRadius: 10, fontSize: 12.5,
  fontWeight: 700, cursor: "pointer", textAlign: "center", marginBottom: 8,
  border: "1.5px solid #E2E8F0", background: "#fff", color: "#475569",
};

const mini = {
  border: "1px solid #E2E8F0", background: "#fff", borderRadius: 6,
  padding: "3px 7px", fontSize: 10.5, color: "#64748B", cursor: "pointer",
  textAlign: "center", width: "100%",
};

function Eyebrow({ children }) {
  return (
    <p style={{
      margin: "0 0 6px", fontSize: 11, fontWeight: 600, letterSpacing: "0.08em",
      textTransform: "uppercase", color: "#94A3B8",
    }}>{children}</p>
  );
}

/** The answer, however this type expresses one. */
function AnswerView({ q }) {
  if (q.type === "mcq") return null;           // shown on the option itself

  if (q.type === "truefalse") {
    const ans = String(q.answer).toLowerCase() === "true";
    return (
      <div style={{ display: "flex", gap: 8, marginTop: 6 }}>
        {[true, false].map((v) => (
          <span key={String(v)} style={{
            padding: "4px 11px", borderRadius: 8, fontSize: 11.5, fontWeight: 600,
            background: v === ans ? "#ECFDF5" : "#F8FAFC",
            border: `1px solid ${v === ans ? "#A7F3D0" : "#E2E8F0"}`,
            color: v === ans ? "#059669" : "#94A3B8",
          }}>{v ? "True" : "False"}{v === ans ? " ✓" : ""}</span>
        ))}
      </div>
    );
  }

  if (q.type === "match") {
    const a = q.column_a ?? [];
    const b = q.column_b ?? [];
    if (!a.length && !b.length) return null;
    return (
      <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 10, marginTop: 7,
                    background: "#fff", border: "1px solid #E2E8F0", borderRadius: 8, padding: "9px 11px" }}>
        <div>
          <b style={{ fontSize: 10.5, color: "#94A3B8", fontWeight: 600 }}>Column A</b>
          {a.map((x, i) => <p key={i} style={{ margin: "5px 0 0", fontSize: 11.5, color: "#334155" }}>{i + 1}. {x}</p>)}
        </div>
        <div>
          <b style={{ fontSize: 10.5, color: "#94A3B8", fontWeight: 600 }}>Column B</b>
          {b.map((x, i) => <p key={i} style={{ margin: "5px 0 0", fontSize: 11.5, color: "#334155" }}>{String.fromCharCode(97 + i)}. {x}</p>)}
        </div>
      </div>
    );
  }

  if (q.answer === undefined || q.answer === null || q.answer === "") return null;

  return (
    <div style={{ marginTop: 6 }}>
      <span style={{ display: "inline-block", background: "#ECFDF5", border: "1px solid #A7F3D0",
                     borderRadius: 8, padding: "4px 10px", fontSize: 11.5, color: "#065F46" }}>
        Answer <b style={{ color: "#047857" }}>{String(q.answer)}</b>
      </span>
      {Array.isArray(q.key_points) && q.key_points.length > 0 && (
        <p style={{ margin: "5px 0 0", fontSize: 11.5, color: "#94A3B8" }}>
          Key points: {q.key_points.join(" · ")}
        </p>
      )}
    </div>
  );
}

/** A question the AI could not write — the paper keeps its place. */
function Blank({ q, onWrite }) {
  return (
    <div style={{ background: "#FFFBEB", border: "1px solid #FDE68A", borderRadius: 10, padding: "11px 13px" }}>
      <span style={{ fontSize: 10, fontWeight: 700, letterSpacing: "0.06em", textTransform: "uppercase", color: "#78350F" }}>
        Not generated by AI yet
      </span>
      <p style={{ margin: "4px 0 9px", fontSize: 11.5, color: "#92400E", lineHeight: 1.55 }}>
        The heading, numbering and answer space print as they are. Write it yourself, or leave it
        for the AI once the service supports {questionTypeLabel(q.type).toLowerCase()}.
      </p>
      {q.type === "match" ? (
        <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 10, background: "#fff",
                      border: "1px solid #FDE68A", borderRadius: 8, padding: "9px 11px" }}>
          {["Column A", "Column B"].map((h) => (
            <div key={h}>
              <b style={{ fontSize: 10.5, color: "#94A3B8", fontWeight: 600 }}>{h}</b>
              <div style={{ height: 1, background: "#E2E8F0", margin: "11px 0" }} />
              <div style={{ height: 1, background: "#E2E8F0", margin: "11px 0" }} />
            </div>
          ))}
        </div>
      ) : (
        <div style={{ height: 36, borderRadius: 6, background:
          "repeating-linear-gradient(transparent, transparent 17px, #FDE68A 17px, #FDE68A 18px)" }} />
      )}
      {onWrite && (
        <button type="button" onClick={onWrite}
          style={{ ...mini, width: "auto", marginTop: 9, borderColor: "#FDE68A", color: "#92400E" }}>
          Write it myself
        </button>
      )}
    </div>
  );
}

function QuestionRow({ q, busy, onRewrite, onReplace, onDrop, onWrite }) {
  const options = q.options ?? [];
  const correct = q.answer_index;
  const text = q.question ?? q.sentence ?? q.statement ?? "";
  const missing = q.pending === true;

  return (
    <div style={{ display: "grid", gridTemplateColumns: "26px minmax(0,1fr) 74px", gap: 10,
                  padding: "10px 0", alignItems: "start", borderTop: "1px solid #F1F5F9",
                  opacity: busy ? 0.5 : 1 }}>
      <span style={{ fontSize: 12, fontWeight: 700, color: "#334155", textAlign: "right",
                     fontVariantNumeric: "tabular-nums" }}>{q.number}.</span>

      <div style={{ minWidth: 0 }}>
        {missing ? (
          <Blank q={q} onWrite={onWrite} />
        ) : (
          <>
            <p style={{ margin: "0 0 7px", fontSize: 13, color: "#0F172A" }}>{text}</p>
            {options.length > 0 && (
              <div style={{ display: "grid", gridTemplateColumns: "repeat(2, minmax(0,1fr))", gap: 6 }}>
                {options.map((opt, i) => {
                  const right = i === correct;
                  return (
                    <span key={i} style={{
                      border: `1px solid ${right ? "#A7F3D0" : "#E2E8F0"}`,
                      background: right ? "#ECFDF5" : "#F8FAFC",
                      color: right ? "#059669" : "#64748B",
                      fontWeight: right ? 600 : 400,
                      borderRadius: 7, padding: "6px 9px", fontSize: 11.5,
                    }}>
                      {String.fromCharCode(65 + i)}) {typeof opt === "string" ? opt : opt?.text ?? ""}
                      {right ? " ✓" : ""}
                    </span>
                  );
                })}
              </div>
            )}
            <AnswerView q={q} />
          </>
        )}
      </div>

      <div style={{ display: "flex", flexDirection: "column", gap: 4 }}>
        <span style={{ fontSize: 10.5, fontWeight: 700, color: "#6366F1", textAlign: "right" }}>{q.marks} m</span>
        {!missing && (
          <>
            <button type="button" disabled={busy} onClick={onRewrite} style={mini}>Rewrite</button>
            <button type="button" disabled={busy} onClick={onReplace} style={mini}>Replace</button>
          </>
        )}
        <button type="button" disabled={busy} onClick={onDrop}
          style={{ ...mini, borderColor: "#FECACA", color: "#DC2626" }}>Drop</button>
      </div>
    </div>
  );
}

export default function ReviewStep({
  config, questions, rawResponse,
  onBack, onPrint, onSave, onQuestionsChange, onRegenerate,
  saved, saving, error,
}) {
  const [title, setTitle] = useState(
    `${config?.examNo || config?.label || "Test"} ${config?.subject || ""}`.trim()
    + (config?.chapterNames?.length ? ` — Ch ${config.chapterNames.map((_, i) => i + 1).join(", ")}` : "")
  );
  const [busyAt, setBusyAt] = useState(null);

  const sections = useMemo(() => groupIntoSections(questions), [questions]);
  const total = useMemo(
    () => questions.reduce((sum, q) => sum + (Number(q.marks) || 0), 0),
    [questions]
  );
  const target = config?.totalMarks ?? 0;
  const short = Math.abs(total - target) >= 0.01;

  // Plain text, for when the service returned prose rather than questions.
  const prose = !questions.length && typeof rawResponse === "string" ? rawResponse : null;

  const asPaper = () => ({
    title,
    subject: config?.subject ?? null,
    total_marks: total,
    minutes: config?.minutes ?? null,
    class_label: config?.classLevel ?? null,
    chapter_names: config?.chapterNames ?? [],
    negative_marking: config?.negativeMarking ?? false,
    paper_text: prose,
    questions: questions.length ? questions : null,
  });

  const act = async (index, fn) => {
    setBusyAt(index);
    try { await fn(); } finally { setBusyAt(null); }
  };

  const dropAt = (index) =>
    onQuestionsChange(questions.filter((_, i) => i !== index));

  const writeAt = (index) =>
    onQuestionsChange(questions.map((q, i) => (i === index ? { ...q, pending: false, question: "" } : q)));

  // The review list is flat; sections are a view over it. An action needs the
  // index in the flat list, so each rendered question carries it.
  let flat = -1;

  return (
    <div style={{ display: "flex", flexWrap: "wrap", gap: 20, alignItems: "flex-start" }}>

      <div style={{ flex: "1 1 520px", minWidth: 0 }}>
        <div style={card}>
          <h2 style={{ margin: 0, textAlign: "center", fontSize: 17, fontWeight: 700,
                       color: "#0F172A", fontFamily: "var(--font-space-grotesk)" }}>
            {title || "Question paper"}
          </h2>
          <div style={{ display: "flex", flexWrap: "wrap", gap: 10, justifyContent: "space-between",
                        fontSize: 11.5, color: "#334155", borderBottom: "1px solid #0F172A",
                        padding: "8px 0 6px", margin: "9px 0 10px" }}>
            {config?.classLevel && <span>{config.classLevel}</span>}
            {config?.chapterNames?.length > 0 && (
              <span>{config.chapterNames.length === 1 ? "Chapter" : "Chapters"}: {config.chapterNames.join(", ")}</span>
            )}
            <span>Max marks: {target}</span>
            {config?.minutes ? <span>Time: {config.minutes} min</span> : null}
          </div>
          <p style={{ margin: "0 0 14px", textAlign: "center", fontSize: 11, color: "#94A3B8" }}>
            Sections follow the blueprint. Printing drops every control and keeps only the paper.
          </p>

          {prose ? (
            <pre style={{ whiteSpace: "pre-wrap", fontFamily: "inherit", fontSize: 13,
                          color: "#1E293B", lineHeight: 1.7, margin: 0 }}>{prose}</pre>
          ) : sections.length === 0 ? (
            <p style={{ textAlign: "center", padding: "24px 0", fontSize: 13, color: "#94A3B8" }}>
              The paper came back empty. Go back and generate it again.
            </p>
          ) : sections.map((s) => (
            <div key={s.id}>
              <p style={{ margin: "14px 0 0", fontSize: 13, fontWeight: 700, color: "#4F46E5",
                          fontFamily: "var(--font-space-grotesk)" }}>
                Section {s.letter} — {s.label}
              </p>
              <p style={{ margin: "1px 0 7px", fontSize: 11, color: "#94A3B8" }}>
                {s.questions.length} question{s.questions.length === 1 ? "" : "s"} · {s.marks} marks
              </p>
              {s.questions.map((q) => {
                flat += 1;
                const index = flat;
                return (
                  <QuestionRow
                    key={`${s.id}-${index}`}
                    q={q}
                    busy={busyAt === index}
                    onRewrite={() => act(index, () => onRegenerate?.(index, false))}
                    onReplace={() => act(index, () => onRegenerate?.(index, true))}
                    onDrop={() => dropAt(index)}
                    onWrite={() => writeAt(index)}
                  />
                );
              })}
            </div>
          ))}

          {questions.length > 0 && (
            <div style={{ display: "flex", justifyContent: "space-between", alignItems: "baseline",
                          borderTop: "2px solid #0F172A", marginTop: 12, paddingTop: 10 }}>
              <b style={{ fontSize: 13, color: "#0F172A" }}>Total</b>
              <span style={{ fontSize: 11.5, color: "#64748B" }}>
                {questions.length} questions across {sections.length} section{sections.length === 1 ? "" : "s"}
              </span>
              <b style={{ fontSize: 14, color: short ? "#991B1B" : "#0F172A" }}>{total} marks</b>
            </div>
          )}
        </div>
      </div>

      {/* ── right rail ──────────────────────────────────────────── */}
      <div style={{ flex: "1 1 260px", minWidth: 0, display: "flex", flexDirection: "column", gap: 14 }}>

        <div style={card}>
          <Eyebrow>Paper title</Eyebrow>
          {saved ? (
            <p style={{ margin: "0 0 11px", fontSize: 14, fontWeight: 700, color: "#0F172A",
                        fontFamily: "var(--font-space-grotesk)" }}>{saved.title}</p>
          ) : (
            <input value={title} onChange={(e) => setTitle(e.target.value)} placeholder="Paper title"
              style={{ width: "100%", boxSizing: "border-box", marginBottom: 11, padding: "8px 11px",
                       border: "1.5px solid #E2E8F0", borderRadius: 9, fontSize: 13, color: "#0F172A" }} />
          )}

          {saved ? (
            <p style={{ ...btn, background: "#ECFDF5", color: "#059669", border: "1.5px solid #A7F3D0", cursor: "default" }}>
              ✓ Saved
            </p>
          ) : (
            <button type="button" onClick={() => onSave(asPaper())} disabled={saving}
              className="ai-gradient"
              style={{ ...btn, border: 0, color: "#fff", opacity: saving ? 0.6 : 1 }}>
              {saving ? "Saving…" : "Save paper"}
            </button>
          )}

          <button type="button" onClick={() => onPrint(saved ?? asPaper(), "paper")}
            style={{ ...btn, borderColor: "#C7D2FE", color: "#4F46E5" }}>
            Print question paper
          </button>
          <button type="button" onClick={() => onPrint(saved ?? asPaper(), "key")}
            style={{ ...btn, marginBottom: 0 }}>
            Print answer key
          </button>

          {error && <p style={{ margin: "10px 0 0", fontSize: 12, color: "#DC2626" }}>{error}</p>}
        </div>

        {sections.length > 0 && (
          <div style={card}>
            <Eyebrow>Section tally</Eyebrow>
            {sections.map((s) => (
              <div key={s.id} style={{ display: "flex", justifyContent: "space-between", gap: 10,
                                       fontSize: 12, padding: "3px 0", color: "#334155" }}>
                <span>{s.letter} · {s.label}</span>
                <b style={{ fontVariantNumeric: "tabular-nums", color: "#0F172A" }}>{s.marks}</b>
              </div>
            ))}
            <div style={{ display: "flex", justifyContent: "space-between", gap: 10, fontSize: 12,
                          borderTop: "1px solid #0F172A", marginTop: 5, paddingTop: 6, fontWeight: 700 }}>
              <span>Total</span>
              <b style={{ fontVariantNumeric: "tabular-nums", color: short ? "#991B1B" : "#0F172A" }}>{total}</b>
            </div>
            {short && (
              <p style={{ margin: "8px 0 0", fontSize: 11.5, color: "#991B1B" }}>
                A {config?.shortLabel || "paper"} is out of {target}. Dropped questions are not replaced
                automatically — rewrite or go back.
              </p>
            )}
          </div>
        )}

        {config?.examNo && (
          <div style={{ background: "#EEF2FF", border: "1px solid #C7D2FE", borderRadius: 12, padding: "12px 14px" }}>
            <b style={{ display: "block", fontSize: 12, fontWeight: 700, color: "#3730A3" }}>
              Saved to the exam record
            </b>
            <p style={{ margin: "3px 0 0", fontSize: 11.5, lineHeight: 1.55, color: "#4338CA" }}>
              Saving ties this paper to {config.examNo}{config.classLevel ? ` for ${config.classLevel}` : ""}.
              When marks are entered for {config.examNo} later, the paper is already there to open.
            </p>
          </div>
        )}

        <div style={{ background: "#EEF2FF", border: "1px solid #C7D2FE", borderRadius: 12, padding: "12px 14px" }}>
          <b style={{ display: "block", fontSize: 12, fontWeight: 700, color: "#3730A3" }}>
            Syllabus: {config?.syllabus ?? "State"}
          </b>
          <p style={{ margin: "3px 0 0", fontSize: 11.5, lineHeight: 1.55, color: "#4338CA" }}>
            Set once for the school, not per paper. State and CBSE follow different question patterns,
            so it is sent with every generation.
          </p>
        </div>

        <button type="button" onClick={onBack}
          style={{ ...btn, marginBottom: 0, background: "#F8FAFC" }}>
          ← Reconfigure
        </button>
      </div>
    </div>
  );
}
